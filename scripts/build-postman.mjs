// Builds postman/site-stats.postman_collection.json: the same live checks as
// tests/site-stats-live.spec.ts, as a Postman collection that Newman can run. The endpoint paths
// come from scripts/lib/site-stats.mjs and the response schemas from contracts/, so the collection
// cannot drift from the script or the Playwright tests (tests/site-stats-postman.spec.ts checks the
// committed file is exactly what this script writes).
//
//   node scripts/build-postman.mjs          write the collection
//   node scripts/build-postman.mjs --check  exit 1 if the committed file is out of date
//
// No secrets are stored: the token is the variable {{token}}, given to Newman at run time.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_REPO, NEVER_LOWER, endpoints, schema } from './lib/site-stats.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const collectionFile = path.join(root, 'postman', 'site-stats.postman_collection.json');

// Postman's schema checker wants the plain schema, without the draft and id keywords.
function plain(name) {
  const { $schema, $id, title, ...rest } = schema(name);
  return rest;
}

const titles = {
  repo: 'Repository',
  issues: 'Issues (search)',
  pull_requests: 'Pull requests (search)',
  pull_requests_merged: 'Merged pull requests (search)',
  commits: 'Commits (first page)',
  releases: 'Releases (first page)',
};

// The count each request contributes, read from its response inside Postman.
const countCode = {
  issues: 'json.total_count',
  pull_requests: 'json.total_count',
  pull_requests_merged: 'json.total_count',
  commits: "lastPage(pm.response.headers.get('Link')) ?? json.length",
  releases: "lastPage(pm.response.headers.get('Link')) ?? json.length",
};

function testScript(name, ep) {
  const lines = [
    // String.raw keeps the backslashes, so the regex arrives in Postman exactly as written here.
    String.raw`const lastPage = (link) => { const m = /[?&]page=(\d+)[^>]*>;\s*rel="last"/.exec(link || ''); return m ? Number(m[1]) : null; };`,
    `const schema = ${JSON.stringify(plain(ep.contract))};`,
    "pm.test('status is 200', () => pm.response.to.have.status(200));",
    "pm.test('response matches the contract', () => pm.response.to.have.jsonSchema(schema));",
    'const json = pm.response.json();',
  ];
  if (name === 'repo') {
    lines.push(
      "pm.test('it is the repository we asked for', () => pm.expect(json.full_name.toLowerCase()).to.eql(pm.variables.get('repo').toLowerCase()));",
      "pm.test('the default branch is main', () => pm.expect(json.default_branch).to.eql('main'));",
    );
  } else {
    lines.push(
      `const count = ${countCode[name]};`,
      `pm.collectionVariables.set('count_${name}', count);`,
      "pm.test('the count is a non-negative integer', () => { pm.expect(Number.isInteger(count)).to.be.true; pm.expect(count).to.be.at.least(0); });",
    );
    if (ep.contract === 'search-issues') lines.push("pm.test('the search is complete', () => pm.expect(json.incomplete_results).to.be.false);");
    if (name === 'commits') lines.push("pm.test('the commit list is not empty', () => pm.expect(json).to.have.length.above(0));");
    if (NEVER_LOWER.includes(name)) {
      lines.push(
        `const min = pm.variables.get('min_${name}');`,
        `pm.test('not lower than the committed value (min_${name})', function () { if (min === undefined || min === '') this.skip(); pm.expect(count).to.be.at.least(Number(min)); });`,
      );
    }
  }
  if (name === 'pull_requests_merged') {
    lines.push("pm.test('merged pull requests do not exceed all pull requests', () => pm.expect(count).to.be.at.most(Number(pm.collectionVariables.get('count_pull_requests'))));");
  }
  return lines;
}

export function buildCollection(repo = DEFAULT_REPO) {
  const eps = endpoints(repo);
  return {
    info: {
      name: 'Site stats - GitHub API contract checks',
      description: 'The live checks behind scripts/site-stats.mjs. Generated by scripts/build-postman.mjs. Run with Newman: see the README section "API and contract tests for the site totals".',
      schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
    },
    auth: { type: 'bearer', bearer: [{ key: 'token', value: '{{token}}', type: 'string' }] },
    variable: [
      { key: 'base_url', value: 'https://api.github.com' },
      { key: 'repo', value: repo },
    ],
    item: Object.entries(eps).map(([name, ep]) => ({
      name: titles[name],
      request: {
        method: 'GET',
        header: [
          { key: 'Accept', value: 'application/vnd.github+json' },
          { key: 'X-GitHub-Api-Version', value: '2022-11-28' },
        ],
        // The path is the script's own path, with the repository swapped for the variable.
        url: `{{base_url}}${ep.path.split(repo.replace('/', '%2F')).join('{{repo}}').split(repo).join('{{repo}}')}`,
      },
      event: [{ listen: 'test', script: { type: 'text/javascript', exec: testScript(name, ep) } }],
    })),
  };
}

export const render = () => `${JSON.stringify(buildCollection(), null, 2)}\n`;

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    // Line endings are ignored: a Windows checkout may turn the file's LF into CRLF.
    const same = fs.existsSync(collectionFile) && fs.readFileSync(collectionFile, 'utf8').replaceAll('\r\n', '\n') === render();
    if (!same) console.error('build-postman: postman/site-stats.postman_collection.json is out of date. Run `npm run postman`.');
    process.exitCode = same ? 0 : 1;
  } else {
    fs.mkdirSync(path.dirname(collectionFile), { recursive: true });
    fs.writeFileSync(collectionFile, render());
    console.log(`build-postman: wrote ${path.relative(root, collectionFile)}`);
  }
}
