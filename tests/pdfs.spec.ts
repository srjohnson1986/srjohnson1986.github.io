import fs from 'node:fs';
import path from 'node:path';
import { test, expect } from './helpers/test';
import { dist, pdfAliases, shownResumes } from './helpers/data';

const MIN_BYTES = 5_000;
const MAX_PAGES = 2;

// Chromium writes one "/Type /Page" object per page ("/Type /Pages" is the page tree).
const countPages = (pdf: Buffer) => (pdf.toString('latin1').match(/\/Type\s*\/Page(?![s\w])/g) ?? []).length;

/**
 * The document title Chromium writes into the PDF's information dictionary. It is not compressed, and
 * it comes from the <title> of the page that was printed, so it shows which print route a file was made from.
 */
function pdfTitle(pdf: Buffer): string | undefined {
  const text = pdf.toString('latin1');
  const hex = text.match(/\/Title\s*<([0-9A-Fa-f\s]+)>/);
  if (hex) return Buffer.from(hex[1].replace(/\s/g, ''), 'hex').swap16().subarray(2).toString('utf16le');
  const literal = text.match(/\/Title\s*\(((?:\\.|[^\\)])*)\)/);
  return literal?.[1].replace(/\\(.)/g, '$1');
}

for (const version of shownResumes) {
  const file = version.pdf;

  test.describe(`PDF for "${version.route}"`, { tag: ['@req-317'] }, () => {
    test('was generated by the build', () => {
      const onDisk = path.join(dist, 'resume', file);
      expect(fs.existsSync(onDisk), `${onDisk} is missing`).toBe(true);
      expect(fs.statSync(onDisk).size).toBeGreaterThan(MIN_BYTES);
    });

    test('is served as a real PDF with a sensible page count', async ({ request }) => {
      const response = await request.get(`/resume/${file}`);
      expect(response.status()).toBe(200);
      expect(response.headers()['content-type']).toContain('application/pdf');

      const body = await response.body();
      expect(body.subarray(0, 5).toString()).toBe('%PDF-');
      expect(body.length).toBeGreaterThan(MIN_BYTES);

      const pages = countPages(body);
      expect(pages, `${file} has ${pages} pages`).toBeGreaterThanOrEqual(1);
      expect(pages, `${file} has ${pages} pages`).toBeLessThanOrEqual(MAX_PAGES);
    });

    test('was printed from its own version, not another one', () => {
      // If the build printed the same route for every version, every file would still be a real PDF, but
      // each would carry the wrong title.
      const title = pdfTitle(fs.readFileSync(path.join(dist, 'resume', file)));
      expect(title, `${file} has no readable title`).toBeTruthy();
      expect(title).toBe(`Steve Johnson - Resume (${version.label})`);
    });
  });
}

// The QA, Consulting, and Adoption versions were replaced by lane resumes. A link someone saved to the old file name
// (on an application, in an email) must still download a current resume: the old name is a copy of the lane PDF.
test.describe('PDFs kept under their old names', { tag: ['@req-317'] }, () => {
  for (const [oldName, laneFile] of Object.entries(pdfAliases)) {
    test(`${oldName} is a copy of ${laneFile}`, async ({ request }) => {
      const copy = fs.readFileSync(path.join(dist, 'resume', oldName));
      expect(copy.equals(fs.readFileSync(path.join(dist, 'resume', laneFile)))).toBe(true);
      const response = await request.get(`/resume/${oldName}`);
      expect(response.status()).toBe(200);
      expect(response.headers()['content-type']).toContain('application/pdf');
    });
  }
});
